"""
Evaluation script
----------------------------
Measures how well the whole pipeline works on the labelled sample images
and on the scoring benchmark table. Use the output in your report's
"Results" section.

Run:   python evaluate.py
Output: printed summary + data/evaluation_report.md

Metrics
  * Extraction accuracy = nutrient values read correctly / values on the label
    (a value is "correct" if within 3 % or 0.11 of the truth)
  * Verdict accuracy    = unhealthy products score <= 40 (Below Average/Poor)
                          healthy products   score >= 61 (Good/Excellent)
  * Benchmark accuracy  = the same verdict test on data/sample_data.csv, which
                          skips OCR and tests only the scoring rules.
"""

import csv
import os
import sys
from typing import Dict, List, Optional

from health_score import calculate_health_score
from nutrient_parser import NUTRIENT_KEYS
from ocr import is_tesseract_available
from pipeline import run_ocr_pipeline

IMAGE_DIR = "sample_images"
BENCHMARK_CSV = os.path.join("data", "sample_data.csv")
REPORT_PATH = os.path.join("data", "evaluation_report.md")
UNHEALTHY_MAX, HEALTHY_MIN = 40, 61


def value_matches(found: Optional[float], truth: float) -> bool:
    """Within 3 % (or 0.11 absolute) of the true value."""
    return found is not None and abs(found - truth) <= max(0.11, 0.03 * abs(truth))


def verdict_ok(score: Optional[int], expected: str) -> bool:
    """Is the score on the right side for the expected verdict?"""
    if score is None:
        return False
    return score <= UNHEALTHY_MAX if expected == "unhealthy" else score >= HEALTHY_MIN


def evaluate_images() -> List[Dict[str, object]]:
    """Run the pipeline on every labelled image."""
    results = []
    with open(os.path.join(IMAGE_DIR, "ground_truth.csv")) as handle:
        for row in csv.DictReader(handle):
            with open(os.path.join(IMAGE_DIR, row["file"]), "rb") as image_file:
                ocr = run_ocr_pipeline(image_file)
            parsed = ocr["parsed"]
            truth = {k: float(row[k]) for k in NUTRIENT_KEYS if row[k] != ""}
            correct = [k for k, v in truth.items() if value_matches(parsed[k], v)]
            # Extra values read although they are not on the label would be a false find.
            score = calculate_health_score(parsed, is_drink=bool(int(row["is_drink"])))
            results.append({
                "file": row["file"], "kind": row["kind"], "product": row["product"],
                "correct": len(correct), "total": len(truth),
                "wrong": [k for k in truth if k not in correct],
                "score": score["score"], "category": score["category"],
                "expected": row["verdict"], "verdict_ok": verdict_ok(score["score"], row["verdict"]),
            })
    return results


def evaluate_benchmark() -> List[Dict[str, object]]:
    """Score the products in data/sample_data.csv (no OCR involved)."""
    results = []
    with open(BENCHMARK_CSV) as handle:
        for row in csv.DictReader(handle):
            values = {k: (float(row[k]) if row[k] != "" else None) for k in NUTRIENT_KEYS}
            values["normalized"] = True
            score = calculate_health_score(values, is_drink=bool(int(row["is_drink"])))
            results.append({"product": row["product"], "score": score["score"], "category": score["category"],
                            "expected": row["expected"], "ok": verdict_ok(score["score"], row["expected"])
                            if row["expected"] != "moderate" else (score["score"] is not None and 21 <= score["score"] <= 80)})
    return results


def summarise(images: List[Dict[str, object]], bench: List[Dict[str, object]]) -> str:
    """Build the markdown report."""
    lines = ["# Evaluation Report", "",
             "Generated by `python evaluate.py` on the synthetic sample labels in `sample_images/`.", ""]
    for kind in ("clean", "photo"):
        subset = [r for r in images if r["kind"] == kind]
        if not subset:
            continue
        ok = sum(r["correct"] for r in subset); total = sum(r["total"] for r in subset)  # type: ignore[misc]
        verdicts = sum(1 for r in subset if r["verdict_ok"])
        lines.append(f"- **{kind.capitalize()} labels ({len(subset)}):** nutrient extraction "
                     f"{ok}/{total} = {100 * ok / total:.1f}% correct; verdict correct {verdicts}/{len(subset)}")
    if bench:
        good = sum(1 for r in bench if r["ok"])
        lines.append(f"- **Scoring benchmark ({len(bench)} products, no OCR):** {good}/{len(bench)} on the right side")
    lines += ["", "## Per-image results", "", "| Image | Product | Values correct | Score | Category | Expected | Verdict |",
              "|---|---|---|---|---|---|---|"]
    for r in images:
        wrong = f" (wrong: {', '.join(r['wrong'])})" if r["wrong"] else ""  # type: ignore[arg-type]
        lines.append(f"| {r['file']} | {r['product']} | {r['correct']}/{r['total']}{wrong} | {r['score']} | "
                     f"{r['category']} | {r['expected']} | {'OK' if r['verdict_ok'] else 'WRONG'} |")
    lines += ["", "## Scoring benchmark", "", "| Product | Score | Category | Expected | Result |", "|---|---|---|---|---|"]
    for r in bench:
        lines.append(f"| {r['product']} | {r['score']} | {r['category']} | {r['expected']} | {'OK' if r['ok'] else 'WRONG'} |")
    lines += ["", "Note: sample labels are synthetic. Accuracy on real photos will usually be lower; "
              "test real labels manually (see TESTING.md)."]
    return "\n".join(lines)


def main() -> int:
    if not is_tesseract_available():
        print("Tesseract is not installed/configured - cannot run the image evaluation.")
        return 1
    images = evaluate_images()
    bench = evaluate_benchmark() if os.path.exists(BENCHMARK_CSV) else []
    report = summarise(images, bench)
    with open(REPORT_PATH, "w") as handle:
        handle.write(report + "\n")
    print(report)
    print(f"\nSaved to {REPORT_PATH}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
